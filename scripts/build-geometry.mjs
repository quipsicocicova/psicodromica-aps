// Run from any directory: node /path/to/project/scripts/build-geometry.mjs
// Requires the installed Playwright Chromium browser. No web server/network used.
import { readFile, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';
import { narrativePaths, radialShape, bulbPaths, valuePaths, sampleCounts } from '../geometry-source.mjs';

// Keep the final mark identical to the original asset, not a redrawn approximation.
const logoSource = await readFile(new URL('../assets/logo-psicodromica.svg', import.meta.url), 'utf8');
const logoPaths = [...logoSource.matchAll(/<path\b([^>]+)\/>/g)].map(([, attrs]) => ({
  d: attrs.match(/\bd="([^"]+)"/)[1],
  fill: attrs.match(/\bfill="([^"]+)"/)[1]
}));
if (logoPaths.length !== 2) throw new Error('Expected the original gear and neural paths');
const browser = await chromium.launch({ args: ['--no-sandbox'] });
try {
  // All SVG length sampling happens offline, in this single browser page.
  const page = await browser.newPage();
  const sampled = await page.evaluate(({ narrativePaths, bulbPaths, valuePaths, sampleCounts, logoPaths }) => {
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    document.body.append(svg);
    function sample(d, count) {
      const path = document.createElementNS(svg.namespaceURI, 'path');
      path.setAttribute('d', d);
      svg.append(path);
      const length = path.getTotalLength();
      if (!Number.isFinite(length) || length <= 0) throw new Error(`Invalid path: ${d}`);
      const points = Array.from({ length: count }, (_, i) => {
        const p = path.getPointAtLength(length * i / (count - 1));
        return [p.x, p.y];
      });
      path.remove();
      return points;
    }
    const pair = (paths, count) => ({ from: sample(paths.from, count), to: sample(paths.to, count) });
    try {
      return {
        narrative: narrativePaths.map(d => sample(d, sampleCounts.narrative)),
        logoGear: sample(logoPaths[0].d, sampleCounts.narrative).map(([x, y]) => [384 + (x - 606.5) * .44, 318 + (y - 487.5) * .44]),
        bulb: pair(bulbPaths, sampleCounts.bulb),
        values: Object.fromEntries(Object.entries(valuePaths).map(([name, paths]) => [name, pair(paths, sampleCounts.values)]))
      };
    } finally {
      svg.remove();
    }
  }, { narrativePaths, bulbPaths, valuePaths, sampleCounts, logoPaths });

  // Preserve the original index-resampling algorithm, NOT SVG arc-length
  // sampling: chairs and teeth must retain their exact point correspondence.
  sampled.narrative.push(radialShape(false), radialShape(true));
  const round = points => points.map(point => point.map(value => {
    if (!Number.isFinite(value)) throw new Error('Non-finite coordinate');
    return Number(value.toFixed(2));
  }));
  const roundPair = pair => ({ from: round(pair.from), to: round(pair.to) });
  const geometry = {
    narrative: sampled.narrative.map(round),
    logo: { paths: logoPaths, gear: round(sampled.logoGear) },
    bulb: roundPair(sampled.bulb),
    values: Object.fromEntries(Object.entries(sampled.values).map(([name, pair]) => [name, roundPair(pair)]))
  };
  if (geometry.narrative.length !== 7 || geometry.narrative.some(points => points.length !== sampleCounts.narrative)) {
    throw new Error('Expected seven 1600-point narrative outlines');
  }
  const output = new URL('../assets/thread-geometry.js', import.meta.url);
  const content = '// Generated by node scripts/build-geometry.mjs; do not edit.\n'
    + `window.PSICODROMICA_GEOMETRY = ${JSON.stringify(geometry)};\n`;
  await writeFile(output, content);
  console.log(`Generated ${output.pathname} (${Buffer.byteLength(content)} bytes)`);
} finally {
  await browser.close();
}
