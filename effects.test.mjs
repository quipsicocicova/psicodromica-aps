import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const base = process.env.TEST_URL || 'http://localhost:5176';
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    window.curveMeasurements = 0;
    const original = SVGGeometryElement.prototype.getPointAtLength;
    SVGGeometryElement.prototype.getPointAtLength = function (...args) { window.curveMeasurements++; return original.apply(this, args); };
  });
  await page.goto(base, { waitUntil: 'domcontentloaded' });
  const initial = await page.locator('#morph-line').evaluate(el => ({ height: el.getBBox().height, phase: document.querySelector('.story').dataset.intro }));
  assert.ok(initial.height < 15, 'The first picture must be a simple line, not an existing brain silhouette');
  assert.notEqual(initial.phase, 'complete');
  assert.deepEqual(await page.locator('[data-brain-phrase]').evaluateAll(nodes => nodes.map(e => Number(getComputedStyle(e).opacity))), [1, 1]);
  await page.waitForTimeout(700);
  assert.equal(await page.locator('.story').getAttribute('data-intro'), 'forming');
  const partial = await page.locator('#morph-line').getAttribute('d');
  await page.waitForFunction(() => document.querySelector('.story').dataset.intro === 'complete');
  assert.notEqual(await page.locator('#morph-line').getAttribute('d'), partial);
  assert.ok(await page.locator('#morph-line').evaluate(e => e.getTotalLength()) > 3500);
  assert.equal(await page.evaluate(() => curveMeasurements), 0, 'No expensive curve sampling may run at startup');
  assert.deepEqual(await page.evaluate(() => PSICODROMICA_GEOMETRY.narrative.map(shape => shape.length)), Array(7).fill(1600));
  assert.equal(await page.locator('.header-caption').count(), 0);
  await page.evaluate(() => window.originalHeader = document.querySelector('.story-header'));
  async function jump(position) {
    await page.evaluate(position => {
      const s = document.querySelector('.story');
      scrollTo({ top: (s.offsetHeight - s.querySelector('.story-sticky').offsetHeight) * position / 7, behavior: 'instant' });
    }, position);
    await page.waitForTimeout(150);
  }
  const brainBox = await page.locator('#morph-line').evaluate(e => ({ width: e.getBBox().width, height: e.getBBox().height }));
  assert.ok(brainBox.width / brainBox.height > 1.2 && brainBox.width / brainBox.height < 1.5, 'Side-view brain proportions follow the uploaded reference, without the old baseline');
  await jump(1);
  assert.ok(await page.locator('#eye-detail').evaluate(e => Number(getComputedStyle(e).opacity)) > .99);
  assert.equal(await page.locator('#eye-detail circle').count(), 2);
  const eyeBox = await page.locator('#morph-line').evaluate(e => ({ width: e.getBBox().width, height: e.getBBox().height }));
  assert.ok(eyeBox.width / eyeBox.height > 2.5, 'The second figure is a wide almond-shaped eye, not a profile');
  assert.equal(await page.locator('.chapter-label').nth(1).textContent(), '02 / lo sguardo');
  await jump(2);
  assert.equal(await page.locator('#eye-detail').evaluate(e => getComputedStyle(e).opacity), '0');
  assert.equal(await page.locator('.discipline-bubble').count(), 3);
  assert.ok(await page.locator('#discipline-bubbles').evaluate(e => Number(getComputedStyle(e).opacity)) > .99);
  assert.equal(await page.locator('#discipline-bubbles').evaluate(e => !e.closest('#gear-assembly')), true);
  assert.equal(await page.locator('#discipline-bubbles').textContent(), 'Ψ', 'Only symbols remain; no discipline names');
  assert.equal(await page.locator('.bubble-cloud').count(), 3);
  assert.equal(await page.locator('.bubble-cloud').evaluateAll(nodes => nodes.every(e => getComputedStyle(e).stroke === 'none')), true);
  assert.equal(await page.locator('.bubble-cloud').evaluateAll(nodes => new Set(nodes.map(e => getComputedStyle(e).fill)).size), 3, 'Each symbol cloud has its own palette tone');
  assert.equal(await page.locator('.asclepius .medical-snake').count(), 1);
  assert.equal(await page.locator('.asclepius .medical-staff').count(), 1);
  await jump(3);
  const allWindows = await page.locator('#city-windows rect').count();
  assert.equal(Number(await page.locator('#city-windows').getAttribute('data-lit')), 0, 'The skyline appears before all windows illuminate');
  const cityScroll = await page.evaluate(() => scrollY);
  await page.waitForTimeout(850);
  const partlyLit = Number(await page.locator('#city-windows').getAttribute('data-lit'));
  assert.ok(partlyLit > 0 && partlyLit < allWindows, 'Windows appear gradually even without scrolling');
  await page.waitForFunction(() => document.querySelector('#city-windows').dataset.state === 'lit');
  assert.equal(await page.evaluate(() => scrollY), cityScroll, 'Lighting must never move the story');
  assert.equal(Number(await page.locator('#city-windows').getAttribute('data-lit')), allWindows);
  assert.ok(await page.locator('#city-windows').evaluate(e => Number(getComputedStyle(e).opacity)) > .99);
  assert.equal(await page.locator('#city-windows rect').evaluateAll(nodes => nodes.every(e => getComputedStyle(e).stroke === 'none')), true);
  await jump(2);
  assert.equal(await page.locator('#city-windows').evaluate(e => getComputedStyle(e).opacity), '0');
  assert.equal(await page.locator('#city-windows').getAttribute('data-state'), 'idle');
  assert.equal(await page.locator('#city-windows').getAttribute('data-lit'), '0');
  await jump(3);
  assert.equal(await page.locator('#city-windows').getAttribute('data-state'), 'lighting', 'Returning to the city rearms the sequence');
  await jump(4);
  const tablePoints = await page.evaluate(() => PSICODROMICA_GEOMETRY.narrative[5]);
  assert.ok(Math.max(...tablePoints.map(([x, y]) => Math.hypot(x - 384, y - 318))) < 179, 'Chairs are close to the rim, not on long spokes');
  for (let i = 0; i < 8; i++) {
    const angle = -Math.PI / 2 + i * Math.PI / 4;
    const backs = tablePoints.map(([x, y]) => [(x - 384) * Math.cos(angle) + (y - 318) * Math.sin(angle), -(x - 384) * Math.sin(angle) + (y - 318) * Math.cos(angle)]).filter(([r, t]) => r > 151 && Math.abs(t) < 28.5);
    assert.ok(backs.length > 20);
    assert.ok(backs.every(([r, t]) => Math.abs(Math.hypot(r - 150, t) - 28) < .2), 'Each chair back is a true semicircle');
  }
  const gear = await page.evaluate(() => PSICODROMICA_GEOMETRY.narrative[6]);
  assert.equal(createHash('sha256').update(JSON.stringify(gear)).digest('hex'), '1af0bf6a7aff73973316931cd18412882110d00f35e175732413bfd407def703', 'The approved gear geometry is unchanged point for point');
  assert.ok(await page.locator('#table-core').evaluate(e => Number(getComputedStyle(e).opacity)) > .99);
  assert.equal(await page.locator('.table-core-pulse').evaluate(e => getComputedStyle(e).animationName), 'core-breathe');
  assert.equal(await page.locator('.table-core-halo').evaluate(e => getComputedStyle(e).filter), 'blur(8px)');
  await jump(7);
  await page.waitForFunction(() => document.querySelector('.story').dataset.gearMotion === 'spinning');
  await page.waitForTimeout(700);
  assert.ok(await page.locator('#gear-aura').evaluate(e => Number(getComputedStyle(e).opacity)) > .3);
  assert.equal(await page.locator('.gear-spark').count(), 18);
  assert.ok(await page.locator('.gear-spark').evaluateAll(nodes => nodes.some(e => Number(getComputedStyle(e).opacity) > .2)), 'Sparks flash as the yellow halo grows');
  await jump(6);
  assert.equal(await page.locator('.gear-spark').evaluateAll(nodes => nodes.every(e => Number(getComputedStyle(e).opacity) === 0 && e.getAnimations().length === 0)), true, 'Reversing cancels sparks immediately');
  await jump(7);
  assert.equal(await page.locator('#gear-sparks').getAttribute('data-state'), 'sparking');
  assert.equal(await page.locator('#art-caption').isVisible(), false);
  assert.equal(await page.locator('.closing-tagline').count(), 1);
  assert.equal(await page.locator('body').innerText().then(t => (t.replace(/\s+/g, ' ').match(/discipline in dialogo, pensiero in movimento/gi) || []).length), 2, 'The extended logo payoff and the arrival eyebrow intentionally share this phrase');
  await page.waitForFunction(() => document.querySelector('.story').dataset.gearMotion === 'stopped');
  assert.equal(await page.locator('#gear-aura').evaluate(e => getComputedStyle(e).opacity), '0');
  assert.equal(await page.locator('.gear-spark').evaluateAll(nodes => nodes.every(e => Number(getComputedStyle(e).opacity) === 0 && e.getAnimations().length === 0)), true);
  await page.locator('.skip-story').click();
  await page.waitForFunction(() => document.querySelector('[data-header-action]').textContent === 'Rivedi il racconto');
  assert.equal(await page.locator('header').count(), 1);
  assert.equal(await page.locator('#associazione nav').count(), 0);
  assert.equal(await page.evaluate(() => originalHeader === document.querySelector('.story-header')), true);
  assert.equal(await page.locator('.story-header').evaluate(e => getComputedStyle(e).position), 'fixed');
  assert.equal(await page.locator('.story-header').evaluate(e => e.getBoundingClientRect().top), 0);
  await page.locator('.skip-story').click();
  // Chromium may retain up to 2px when cancelling the native smooth skip.
  await page.waitForFunction(() => scrollY <= 2);
  assert.equal(await page.locator('[data-header-action]').textContent(), 'Salta il racconto');
  assert.notEqual(await page.locator('.story').getAttribute('data-intro'), 'complete', 'Replay restarts the line-to-brain formation');
  const title = await page.locator('.contact-layout h2').boundingBox();
  const button = await page.locator('.contact-action').boundingBox();
  assert.ok(button.x > title.x + title.width, 'Final button is beside the title, not attached underneath it');
  assert.equal(await page.locator('.contact-action .thread-icon,.contact-cta').count(), 0);
  assert.equal(await page.locator('.contact-action').getAttribute('href'), 'iscrizione.html');
  await page.setViewportSize({ width: 320, height: 568 });
  await page.locator('.header-menu-toggle').click();
  assert.equal(await page.locator('.header-nav').isVisible(), true);
  assert.equal(await page.locator('.header-menu-toggle').getAttribute('aria-expanded'), 'true');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.header-nav').isVisible(), false);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 320);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.locator('[data-chapter="3"]').click();
  assert.equal(await page.locator('#city-windows').getAttribute('data-state'), 'static');
  assert.equal(Number(await page.locator('#city-windows').getAttribute('data-lit')), allWindows);
  assert.equal(await page.locator('#city-windows rect').evaluateAll(nodes => nodes.every(e => e.getAnimations().length === 0)), true);
  await page.locator('[data-chapter="4"]').click();
  assert.equal(await page.locator('.table-core-pulse').evaluate(e => getComputedStyle(e).animationName), 'none');
  await page.locator('[data-chapter="7"]').click();
  assert.equal(await page.locator('#gear-aura').evaluate(e => getComputedStyle(e).opacity), '0');
  assert.equal(await page.locator('#gear-aura').evaluate(e => e.getAnimations().length), 0);
  assert.equal(await page.locator('#gear-sparks').evaluate(e => getComputedStyle(e).display), 'none');
  assert.equal(await page.locator('.gear-spark').evaluateAll(nodes => nodes.every(e => e.getAnimations().length === 0)), true);
  await page.goto(new URL('about.html', base).href);
  assert.deepEqual(await page.locator('.about-footnote + .about-initiatives a').evaluateAll(nodes => nodes.map(e => e.getAttribute('href'))), ['tavole-rotonde.html', 'osservatorio.html']);
  assert.equal(await page.evaluate(() => curveMeasurements), 0, 'Manifesto also uses precomputed geometry');
  await page.goto(new URL('osservatorio.html', base).href);
  const darkSurface = await page.locator('body').evaluate(el => getComputedStyle(el).backgroundColor);
  assert.deepEqual(await page.locator('.read-label').evaluateAll(nodes => nodes.map(e => getComputedStyle(e).backgroundColor)), Array(3).fill(darkSurface));
  for (const route of ['index.html', 'about.html', 'tavole-rotonde.html', 'osservatorio.html', 'iscrizione.html', 'parole.html', 'ricerca.html', 'confini.html']) {
    await page.goto(new URL(route, base).href);
    assert.equal(await page.locator('footer .footer-description').count(), 1);
    assert.equal(await page.locator('footer .footer-description').innerText(), 'Associazione di promozione sociale - Divulgazione e confronto, non consulenza clinica. I contenuti non sostituiscono il parere di un professionista.');
    assert.equal(await page.locator('footer > span').count(), 0);
    assert.equal(await page.locator('footer small').evaluate(e => getComputedStyle(e).textAlign), 'right');
    assert.equal(await page.locator('footer .wordmark').isVisible(), true);
    assert.equal(await page.evaluate(() => curveMeasurements), 0);
  }
  assert.deepEqual(errors, []);
  console.log('PASS: line-to-brain formation, precomputed geometry, speech bubbles, progressive windows, pulsing table core, gear halo, unique persistent header and replay, side CTA, About links, dark Osservatorio buttons, unified footer, mobile menu, reduced motion.');
} finally { await browser.close(); }
